#!/usr/bin/env node
/**
 * Regenerate EXPECTED_PROTECTED_COMMERCE_SHA256 for Deno ingest gate.
 * Writes supabase/functions/_shared/cursorProtectedCommerce.ts (hashes only section via stdout paste)
 * and prints the map for package-artifact validation.
 *
 * Run from repo root or runtime package:
 *   node tools/speedvendors-storefront-runtime/scripts/gen-protected-commerce-hashes.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RUNTIME_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(RUNTIME_ROOT, '../..');
const OUT = path.join(REPO_ROOT, 'supabase/functions/_shared/cursorProtectedCommerce.ts');

const FILES = [
  'src/speedvendors/commerce.ts',
  'src/speedvendors/storeApiCommerce.ts',
  'src/speedvendors/runtimeConfig.ts',
  'src/speedvendors/types.ts',
  'src/speedvendors/hooks.tsx',
];

function sha256File(abs) {
  return createHash('sha256').update(readFileSync(abs)).digest('hex');
}

const map = {};
for (const rel of FILES) {
  const abs = path.join(RUNTIME_ROOT, rel);
  if (!existsSync(abs)) {
    console.error(`missing ${abs}`);
    process.exit(1);
  }
  map[rel] = sha256File(abs);
  console.log(`${map[rel]}  ${rel}`);
}

const entries = FILES.map(
  (rel) =>
    `  '${rel}':\n    '${map[rel]}',`,
).join('\n');

const body = `/**
 * Expected SHA-256 of protected SpeedVendors commerce sources (runtime mirror).
 * Regenerated by: node tools/speedvendors-storefront-runtime/scripts/gen-protected-commerce-hashes.mjs
 *
 * On artifact ingest, if packageManifest.protectedCommerceSha256 is present and
 * differs from EXPECTED_HASHES → version fails (do not advance draft pointer).
 * Missing map (older packages) → skip (backward compatible).
 */

export const PROTECTED_COMMERCE_FILES = [
  'src/speedvendors/commerce.ts',
  'src/speedvendors/storeApiCommerce.ts',
  'src/speedvendors/runtimeConfig.ts',
  'src/speedvendors/types.ts',
  'src/speedvendors/hooks.tsx',
] as const;

/** Path → sha256 hex (of source file bytes at runtime tip). */
export const EXPECTED_PROTECTED_COMMERCE_SHA256: Record<string, string> = {
${entries}
};

export type ProtectedCommerceAssertResult =
  | { ok: true; skipped: true; reason: 'missing_map' }
  | { ok: true; skipped: false }
  | { ok: false; error: string; mismatches: string[] };

/**
 * When manifest.protectedCommerceSha256 is present, every expected path must match.
 * Unknown extra keys in the package map are ignored; missing expected keys → fail.
 */
export function assertProtectedCommerceHashes(
  packageManifest: Record<string, unknown> | null | undefined,
  expected: Record<string, string> = EXPECTED_PROTECTED_COMMERCE_SHA256,
): ProtectedCommerceAssertResult {
  if (!packageManifest || typeof packageManifest !== 'object') {
    return { ok: true, skipped: true, reason: 'missing_map' };
  }
  const raw = packageManifest.protectedCommerceSha256;
  if (raw == null || typeof raw !== 'object' || Array.isArray(raw)) {
    return { ok: true, skipped: true, reason: 'missing_map' };
  }
  const got = raw as Record<string, unknown>;
  const mismatches: string[] = [];
  for (const [rel, want] of Object.entries(expected)) {
    const actual = got[rel];
    if (typeof actual !== 'string' || actual.toLowerCase() !== want.toLowerCase()) {
      mismatches.push(
        \`\${rel}: expected \${want.slice(0, 12)}… got \${
          typeof actual === 'string' ? actual.slice(0, 12) + '…' : String(actual)
        }\`,
      );
    }
  }
  if (mismatches.length > 0) {
    return {
      ok: false,
      error: 'protected_commerce_hash_mismatch',
      mismatches,
    };
  }
  return { ok: true, skipped: false };
}
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
